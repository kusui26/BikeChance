-- **森の入れ替えを W11 に回した**（2026-11-10、利用者）。新しい森（`lgbm-v1-20261103`）を
-- shadow に置くと、HELLO とドコモの推論が毎周期重なってメモリの山が積み上がり、47 分で引き金
-- （1.6 GB）に当たった（所見 244）。先に推論の位相を直し、それから shadow 3 日 → 昇格になる。
--
-- 配信中の森（`lgbm-v1-20261005`、最終学習日 10-05）は、0058 の 42 日では **11/16（月）00:00**
-- から鳴る。入れ替えは位相の直しと shadow 3 日の後なので、**鳴っても打つ手が無い**（0048 が
-- 避けた「狼少年」。6 時間ごとに鳴り続けると、ほかの警報が読まれなくなる）。
--
--   49 日 ＝ 0058 の 42 日 ＋ 1 週（入れ替えを回した W11 のぶん）→ 初めて鳴るのは 11/23（月）00:00
--
-- **W11 の昇格の後に 42 日へ戻す**（次の移行で。開発プラン §11.2 の表）。昇格が 11/23 に
-- 間に合わなければ鳴る——それは「回した入れ替えが、さらに遅れている」報せとして正しい。
--
-- 0058 と同じく `app_config` の値で持つので、**42 のままの環境だけを 49 にする**（手で別の値に
-- してあれば触らない）。検査の関数（`check_forest_freshness`）は変えない。

update public.app_config
   set value = '49', updated_at = now()
 where key = 'forest_stale_days' and value = '42';
