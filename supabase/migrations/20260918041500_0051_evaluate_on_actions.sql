-- 0051 — 日次評価を GitHub Actions に移す（`monitored_jobs` の覚え書きを直す）
-- ────────────────────────────────────────────────────────────────
-- **表の形は変えない。** 直すのは 0050 が入れた `evaluate_daily` の説明だけである。
--
-- 0050 は「Vercel Cron 04:40 JST」と書いた。**そこでは動かなかった**——2026-09-16 を
-- 実測するとメモリの山が **2.26 GB** で、Vercel の枠（300 秒・2 GB）に入らない。
-- 初回（09-17 04:40）と 2 回目（09-18 04:40）はどちらも `FUNCTION_INVOCATION_FAILED`
-- で死に、`job_runs` に `running` の行だけを残した（W5 プラン §12 の 171）。
--
-- **`cron_job_name` は NULL のまま。** pg_cron ではないので 0022 の「pg_cron に
-- 登録されているか」の検査の対象外である、という位置づけは変わらない。置き場所が
-- Vercel Cron から GitHub Actions に変わっただけで、**見張りの側から見える形は同じ**。
--
-- **閾値も変えない**（`expected_every = 1 日`、`missing_after = 30 時間`）。GitHub の
-- `schedule` は混雑時に遅れる（実測 1 時間 55 分）が、30 時間はそれを見込んである。
--
-- **覚え書きを直すためだけにマイグレーションを 1 つ使う**のは、`monitored_jobs.note` が
-- **本番にしか無い文字列**だからである。障害のときに最初に読まれる場所が、動かない
-- 起動方法を指していてはいけない。
-- ────────────────────────────────────────────────────────────────

update public.monitored_jobs
   set note = 'GitHub Actions（evaluate-daily.yml）06:40 JST。前日ぶんの実運用 Brier を '
              'model_daily_metrics に入れる。Vercel では山 2.26 GB が枠（2 GB）に入らず '
              '2026-09-17・18 が死んだので移した（D-26）。止まっても配信は無事で、'
              '予測ログ（12 か月）から後で測り直せる（workflow_dispatch の date 入力）'
 where job_name = 'evaluate_daily';
